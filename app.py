
import pickle
from pathlib import Path

import pandas as pd
import streamlit as st

st.set_page_config(
    page_title="Titanic Survival Prediction",
    page_icon="🚢",
    layout="centered"
)

MODEL_PATH = Path(__file__).parent / "svc_trained_model.pkl"


@st.cache_resource
def load_model():
    with open(MODEL_PATH, "rb") as file:
        return pickle.load(file)


st.title("🚢 Titanic Passenger Survival Prediction")
st.write(
    "Enter passenger information to predict whether "
    "the model classifies the passenger as a survivor."
)

st.info("This is an educational machine-learning demonstration.")

with st.form("prediction_form"):
    pclass = st.selectbox(
        "Passenger Class",
        options=["First", "Second", "Third"]
    )

    gender = st.selectbox(
        "Gender",
        options=["Female", "Male"]
    )

    sibling = st.selectbox(
        "Sibling/Spouse Category",
        options=["One", "Three", "Two", "Zero"]
    )

    embarked = st.selectbox(
        "Port of Embarkation",
        options=["Cherbourg", "Queenstown", "Southampton"]
    )

    submitted = st.form_submit_button("Predict Survival")

if submitted:
    # Encodings inferred from the provided sample data.
    class_encoding = {
        "First": 0,
        "Second": 1,
        "Third": 2
    }

    gender_encoding = {
        "Female": 0,
        "Male": 1
    }

    sibling_encoding = {
        "One": 0,
        "Three": 1,
        "Two": 2,
        "Zero": 3
    }

    embarked_encoding = {
        "Cherbourg": 0,
        "Queenstown": 1,
        "Southampton": 2
    }

    passenger = pd.DataFrame([{
        "PClass": class_encoding[pclass],
        "Gender": gender_encoding[gender],
        "Sibling": sibling_encoding[sibling],
        "Embarked": embarked_encoding[embarked]
    }])

    try:
        model = load_model()
        prediction = int(model.predict(passenger)[0])

        if prediction == 1:
            st.success("Prediction: The model predicts survival.")
        else:
            st.error("Prediction: The model predicts non-survival.")

        st.caption(
            "This prediction is generated by a trained model "
            "and is not a guarantee of what would have happened."
        )

    except Exception as error:
        st.error(f"Prediction failed: {error}")
